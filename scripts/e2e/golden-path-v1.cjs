const { chromium } = require(process.argv[2]);
const OUT = process.argv[3], BASE = "https://rivallens-eight.vercel.app";
(async () => {
  const browser = await chromium.launch({ executablePath: process.argv[4] });
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
  page.setDefaultTimeout(90000);
  const nimbus = () => page.locator("li", { hasText: "NimbusDeploy (demo)" });
  await page.goto(`${BASE}/login`);
  await page.getByRole("button", { name: /demo account/i }).click();
  await page.waitForURL(/\/app/);
  await page.getByText("Cloud deployment, Pune").waitFor();
  const runOnce = async (scenario, shot) => {
    await page.goto(`${BASE}/app/demo-lab`);
    await nimbus().getByRole("button", { name: new RegExp(scenario) }).click();
    await page.getByText(/Applied/).waitFor();
    await page.getByRole("link", { name: "Open StackNest dashboard" }).click();
    const t = Date.now();
    await page.getByRole("button", { name: "Run monitor" }).click();
    await page.waitForURL(/\/run\?id=/);
    await page.getByText("differences ignored").waitFor();
    console.log(scenario, `${((Date.now() - t) / 1000).toFixed(1)}s`, (await page.locator("[data-screen=S-10] .rounded-stadium p:first-child").allTextContents()).join(" meaningful / "), "ignored");
    await page.screenshot({ path: `${OUT}/${shot}`, fullPage: true });
  };
  await page.goto(`${BASE}/app/demo-lab`);
  await page.getByRole("button", { name: "Reset all pages" }).click();
  await page.getByText(/original version/).waitFor();
  await runOnce("Cosmetic-only", "s10-cosmetic.png");
  console.log("ledger:", (await page.locator("ul.divide-y li > span:first-child").allTextContents()).join(", "));
  await runOnce("Cut Pro price", "s10-pricecut.png");
  await page.getByRole("link", { name: /See receipt/ }).first().click();
  await page.getByRole("heading", { name: "The saved pages" }).waitFor();
  await page.locator("mark").first().waitFor();
  console.log("S-11:", (await page.locator("[data-screen=S-11] .rounded-stadium").innerText()).replace(/\n/g, " | "));
  console.log("marks:", (await page.locator("mark").allTextContents()).join(" / "));
  console.log("seen on:", await page.locator("dd").first().innerText());
  await page.screenshot({ path: `${OUT}/s11-desktop.png`, fullPage: true });
  await page.getByRole("button", { name: "View original" }).nth(1).click();
  const frame = page.locator("iframe");
  await frame.waitFor();
  console.log("iframe sandbox:", JSON.stringify(await frame.getAttribute("sandbox")), "ribbon inside:", await frame.contentFrame().getByText("Demo data: fictional company").count());
  await page.setViewportSize({ width: 390, height: 844 });
  await page.reload();
  await page.locator("mark").first().waitFor();
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth);
  console.log("phone horizontal overflow px:", overflow);
  await page.screenshot({ path: `${OUT}/s11-phone.png`, fullPage: true });
  await browser.close();
})().catch((e) => { console.error("FAILED", e.message); process.exit(1); });
